// Package pgtest provides the "real PostgreSQL gate + a fresh schema per test" test infrastructure,
// reused by every gated test that needs a real PG, such as internal/store and internal/auth.
//
// Why we cannot just run bare against the same database: PostgreSQL is a persistent shared instance, so rows written by tests, sequences
// and unique indexes all survive into the next run, and a second execution of the same case collides on primary/unique keys
// (`-count=2` or a plain rerun is guaranteed to blow up). The SQLite path creates a brand-new database file per case with t.TempDir(),
// which isolates naturally, so this flaw only surfaces under PG. Here every Open call creates its own schema
// and pins the connection's search_path to that schema; when the case finishes (t.Cleanup) a DROP SCHEMA
// ... CASCADE reclaims it together with all the tables in it, giving the same isolation SQLite's temporary database has.
package pgtest

import (
	"crypto/rand"
	"encoding/hex"
	"fmt"
	"net/url"
	"os"
	"strings"
	"testing"

	"gorm.io/driver/postgres"
	"gorm.io/gorm"
)

// EnvDSN is the environment variable that enables the PostgreSQL path; when unset, callers should skip the PG path.
//
// Unset by default: both local and CI run SQLite only and start no database service (AGENTS.md §2.5). To cover the production
// PG driver, point it at a working instance and run manually, e.g.
//
//	TEST_PG_DSN='postgres://user:CHANGE_ME@127.0.0.1:5432/db?sslmode=disable' go test ./internal/store/ ./internal/schedule/ ./internal/digest/
const EnvDSN = "TEST_PG_DSN"

// Open returns (nil, false) when TEST_PG_DSN is unset, letting callers skip the PG path;
// when set it returns a *gorm.DB bound to a fresh schema and drops that schema in t.Cleanup.
// The schema name is built from the test name plus a random suffix, so running the same case concurrently does not overwrite it.
func Open(t *testing.T) (*gorm.DB, bool) {
	t.Helper()
	dsn := strings.TrimSpace(os.Getenv(EnvDSN))
	if dsn == "" {
		t.Logf("%s not set: skipping the PostgreSQL path on this machine", EnvDSN)
		return nil, false
	}

	schema := schemaName(t)

	// The admin connection is used only to create/drop schemas and never carries the data under test.
	admin, err := gorm.Open(postgres.Open(dsn), &gorm.Config{})
	if err != nil {
		t.Fatalf("open postgres: %v", err)
	}
	if err := admin.Exec("CREATE SCHEMA " + quoteIdent(schema)).Error; err != nil {
		t.Fatalf("create schema %s: %v", schema, err)
	}
	t.Cleanup(func() {
		if err := admin.Exec("DROP SCHEMA " + quoteIdent(schema) + " CASCADE").Error; err != nil {
			t.Errorf("drop schema %s: %v", schema, err)
		}
		closeGorm(admin)
	})

	db, err := gorm.Open(postgres.Open(withSearchPath(dsn, schema)), &gorm.Config{})
	if err != nil {
		t.Fatalf("open postgres (schema %s): %v", schema, err)
	}
	t.Cleanup(func() { closeGorm(db) })
	return db, true
}

// withSearchPath writes search_path back into the DSN as a connection parameter; pgx forwards unknown parameters
// to the server as startup runtime parameters, so every new connection in the pool lands on the target schema.
func withSearchPath(dsn, schema string) string {
	if u, err := url.Parse(dsn); err == nil && u.Scheme != "" {
		q := u.Query()
		q.Set("search_path", schema)
		u.RawQuery = q.Encode()
		return u.String()
	}
	// Keyword/value DSNs ("host=... user=...") simply get one more key/value pair appended.
	return dsn + " search_path=" + schema
}

// quoteIdent double-quotes an identifier. Schema names are generated by this package and contain only [a-z0-9_],
// so there is no injection surface; the quotes here only defensively preserve case and dodge keyword conflicts.
func quoteIdent(ident string) string {
	return `"` + ident + `"`
}

// schemaName generates a schema name that is both legal and unique: prefix + sanitized test name + random suffix.
// PostgreSQL identifiers are capped at 63 bytes, so the test name is truncated.
func schemaName(t *testing.T) string {
	var b [6]byte
	if _, err := rand.Read(b[:]); err != nil {
		t.Fatalf("generate schema suffix: %v", err)
	}
	name := strings.ToLower(t.Name())
	var sb strings.Builder
	for _, r := range name {
		switch {
		case r >= 'a' && r <= 'z', r >= '0' && r <= '9', r == '_':
			sb.WriteRune(r)
		default:
			sb.WriteByte('_')
		}
	}
	cleaned := sb.String()
	if len(cleaned) > 40 {
		cleaned = cleaned[:40]
	}
	return fmt.Sprintf("engram_test_%s_%s", cleaned, hex.EncodeToString(b[:]))
}

// closeGorm closes the underlying sql.DB so connections do not pile up in the test process.
func closeGorm(db *gorm.DB) {
	if sqlDB, err := db.DB(); err == nil {
		_ = sqlDB.Close()
	}
}
